// ─────────────────────────────────────────────────────────────────────────
// THE LIST. This is the whole point: adding a service here creates its entire
// pipeline on the next seed run. Nothing is clicked. Nothing is configured in
// the UI. The jobs are a pure function of this file.
//
// removeAction('DELETE') is set on the seed job, so removing a service here
// DELETES its job. The jobs converge on this file in both directions -- the
// same reconciliation idea ArgoCD applies to the cluster, one layer up.
// ─────────────────────────────────────────────────────────────────────────
def services = [
    'edge-gateway',
    'auth-svc',
    'catalog-svc',
    'cart-svc',
    'order-svc',
    'payment-worker',
    'notify-svc',
    'media-svc',
]

def gitHubUser = 'pratikpagariya'
def appsRepo   = "https://github.com/${gitHubUser}/shopglobe-apps.git"
def infraRepo  = "https://github.com/${gitHubUser}/shopglobe-infra.git"

folder('shopglobe') {
    description('Generated by the seed job from jenkins/jobdsl/. Edits made here are overwritten on the next run.')
}

services.each { svc ->
    pipelineJob("shopglobe/${svc}") {
        description("Build -> scan -> push -> GitOps deploy for ${svc}. Generated by Job DSL; do not edit in the UI.")

        parameters {
            // SERVICE is how ONE shared Jenkinsfile knows which service it is
            // building. Eight jobs, one pipeline definition to maintain.
            stringParam('SERVICE', svc, 'Service being built (set by Job DSL)')
            stringParam('GIT_REF', 'main', 'Branch or tag to build')
            booleanParam('DEPLOY', true, 'Commit the new image tag to the gitops repo')
        }

        properties {
            // Two builds of the same service racing to write the gitops repo
            // will conflict on push. Serialise them.
            disableConcurrentBuilds()
        }

        logRotator {
            numToKeep(20)
            artifactNumToKeep(5)
        }

        definition {
            cpsScm {
                scm {
                    git {
                        remote { url(appsRepo) }
                        branch('${GIT_REF}')
                    }
                }
                scriptPath('Jenkinsfile')
                lightweight(false)
            }
        }
    }
}

// Infrastructure gets a differently SHAPED pipeline, not just different steps.
// Today it validates only: fmt, validate, tflint, with no AWS credentials. It
// is named for what it does -- a job called "plan" that never plans is a lie
// someone eventually trusts. removeAction('DELETE') on the seed job removes
// the old terraform-plan job on the next seed run.
//
// Triggered by hand, like every job here: the cluster has no public ingress
// for a GitHub webhook to reach (CICD-FLOW.md).
pipelineJob('shopglobe/terraform-validate') {
    description('fmt -> validate -> tflint on every stack. No plan, no apply, no AWS credentials.')

    parameters {
        // First choice = the default in the Build with Parameters form.
        choiceParam('STACK', ['all', 'prod', 'stage', 'dev', 'legacy'], 'Which stack(s) to validate')
    }

    logRotator {
        numToKeep(20)
    }

    definition {
        cpsScm {
            scm {
                git {
                    remote { url(infraRepo) }
                    branch('main')
                }
            }
            scriptPath('Jenkinsfile.terraform')
            lightweight(false)
        }
    }
}
